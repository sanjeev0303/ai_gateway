// Package domain defines the core entities of the AI governance platform.
//
// The domain types are plain data holders: they carry no persistence, RLS, or
// sqlc concerns. Repositories map between these types and the sqlc-generated
// DTOs in internal/infrastructure/postgres/sqlc, so business logic never
// imports the generated database structs.
package domain

import (
	"time"

	"github.com/google/uuid"
)

// Status and role values. These mirror the CHECK constraints enforced in the
// database; the database remains the source of truth.
const (
	RoleAdmin  = "admin"
	RoleMember = "member"
)

const (
	OrgStatusActive    = "active"
	OrgStatusSuspended = "suspended"
)

const (
	UserStatusActive   = "active"
	UserStatusDisabled = "disabled"
)

const (
	ProjectStatusActive   = "active"
	ProjectStatusArchived = "archived"
)

// NewOrganization carries the caller-supplied fields for creating an
// organization. Status is defaulted by the database to aigw 'active'.
type NewOrganization struct {
	Name string
	Slug string
}

// Organization is a tenant root. Global table: a small set of well-known
// organizations, never tenant-scoped.
type Organization struct {
	ID                         uuid.UUID
	Name                       string
	Slug                       string
	Status                     string
	PrivacyDefault             PrivacyMode
	RetentionConversationsDays int
	RetentionUsageDays         int
	RetentionAuditsDays        int
	RetentionBillingDays       int
	CreatedAt                  time.Time
	UpdatedAt                  time.Time
}

// NewUser carries the caller-supplied fields for creating a user.
type NewUser struct {
	Email       string
	DisplayName string
}

// User is a global identity that may belong to many organizations.
type User struct {
	ID          uuid.UUID
	Email       string
	DisplayName string
	Status      string
	CreatedAt   time.Time
	UpdatedAt   time.Time
	LastLoginAt *time.Time
}

// UserCredential is the authentication projection of an identity: the user
// plus its stored password digest. It is a distinct type from User so the
// digest cannot be attached to a User that reaches an API response -- User has
// no credential field at all, which makes the leak structurally impossible
// rather than a rule to remember.
type UserCredential struct {
	User User
	// PasswordHash is nil for accounts with no password, such as users
	// provisioned through the dev-login path. Such accounts cannot
	// password-authenticate.
	PasswordHash *string
}

// Registration is the one-shot signup write: a new user, their password
// digest, and the organization they own, committed together.
type Registration struct {
	User NewUser
	// PasswordHash is the PBKDF2 digest of the chosen password. It is
	// persisted by this same write so an account can never exist without
	// the credential that created it.
	PasswordHash string
	// RefreshTokenHash and RefreshTokenExpiresAt commit in the same
	// transaction as the account, so a user can never end up created without
	// the session that proves the signup completed. Only the digest is stored.
	RefreshTokenHash      string
	RefreshTokenExpiresAt time.Time
	// OrganizationID is generated by the caller rather than the database so
	// the tenant context can be bound before the organization_members insert;
	// that table is FORCE RLS and its policy reads app.current_org_id().
	OrganizationID   uuid.UUID
	OrganizationName string
	OrganizationSlug string
}

// RefreshToken is one issued refresh credential. Only the digest of the raw
// token is persisted; the raw value exists solely in the response that hands
// it to the browser and must never be logged or stored.
type RefreshToken struct {
	ID        uuid.UUID
	UserID    uuid.UUID
	TokenHash string
	ExpiresAt time.Time
	// RevokedAt is set when the token is retired. A presented token with a
	// non-nil RevokedAt is reuse of an already-rotated credential.
	RevokedAt  *time.Time
	CreatedAt  time.Time
	LastUsedAt *time.Time
}

// NewProject carries the caller-supplied fields for creating a project
// inside an organization.
type NewProject struct {
	Name        string
	Slug        string
	Description string
}

// Project groups usage and scoped access within an organization.
type Project struct {
	ID             uuid.UUID
	OrganizationID uuid.UUID
	Name           string
	Slug           string
	Description    string
	Status         string
	CreatedAt      time.Time
	UpdatedAt      time.Time
}

// UpdateProject carries the caller-supplied fields for updating a project.
type UpdateProject struct {
	Name        *string
	Description *string
}

// NewTeam carries the caller-supplied fields for creating a team.
type NewTeam struct {
	Name        string
	Description string
}

// Team is a tenant-scoped group of users.
type Team struct {
	ID             uuid.UUID
	OrganizationID uuid.UUID
	Name           string
	Description    string
	CreatedAt      time.Time
	UpdatedAt      time.Time
}

// UpdateTeam carries the caller-supplied fields for updating a team.
type UpdateTeam struct {
	Name        *string
	Description *string
}

// OrganizationMember is one row of the organization_members join table.
type OrganizationMember struct {
	OrganizationID uuid.UUID
	UserID         uuid.UUID
	Role           string
	CreatedAt      time.Time
}

// TeamMember is one row of the team_members join table.
type TeamMember struct {
	TeamID         uuid.UUID
	OrganizationID uuid.UUID
	UserID         uuid.UUID
	Role           string
	CreatedAt      time.Time
}

// OrgMember is an organization member with the user's profile attached.
type OrgMember struct {
	OrganizationID uuid.UUID
	User           User
	Role           string
	MemberSince    time.Time
}

// TeamMemberView is a team member with the user's profile attached.
type TeamMemberView struct {
	User        User
	Role        string
	MemberSince time.Time
}

// UserOrganization is an organization a user belongs to, plus their role.
type UserOrganization struct {
	Organization Organization
	Role         string
}

// UpdateOrganization carries partial updates to an organization.
type UpdateOrganization struct {
	Name                       *string
	Slug                       *string
	PrivacyDefault             *string
	RetentionConversationsDays *int32
	RetentionUsageDays         *int32
	RetentionAuditsDays        *int32
	RetentionBillingDays       *int32
}
